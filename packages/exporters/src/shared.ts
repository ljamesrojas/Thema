import { formatHex, formatHex8, type Oklch } from "culori";
import { parseCssColor, SERIF_NAME, type ColorRole, type ThemaSystem } from "@thema/engine";

/** Every color role, in a stable order for output. */
export const COLOR_ROLES: readonly ColorRole[] = [
  "canvas",
  "surface",
  "surface-raised",
  "ink",
  "ink-muted",
  "hairline",
  "primary",
  "primary-ink",
  "accent",
  "success",
  "warning",
  "danger",
  "info",
];

export const THEMES = ["light", "dark"] as const;
export type Theme = (typeof THEMES)[number];

export function parseColor(css: string): Oklch {
  const color = parseCssColor(css);
  if (!color) throw new Error(`exporters: unparseable color ${css}`);
  return color;
}

/**
 * OKLCH → sRGB hex: the only conversion out of OKLCH in Thema. Opaque colors give #rrggbb,
 * translucent ones #rrggbbaa. culori clamps out-of-gamut channels.
 */
export function toHex(css: string): string {
  const color = parseColor(css);
  return (color.alpha ?? 1) < 1 ? formatHex8(color) : formatHex(color);
}

// --- fonts --------------------------------------------------------------------------------

const GENERIC = new Set([
  "system-ui",
  "ui-sans-serif",
  "ui-serif",
  "ui-monospace",
  "ui-rounded",
  "sans-serif",
  "serif",
  "monospace",
  "cursive",
  "fantasy",
]);

const STACK = {
  sans: ["ui-sans-serif", "system-ui", "sans-serif"],
  serif: ["ui-serif", "Georgia", "serif"],
  mono: ["ui-monospace", "SFMono-Regular", "Menlo", "monospace"],
} as const;

type Slot = keyof ThemaSystem["typography"]["families"];

/**
 * A family name with its fallback stack: sans, serif or mono by slot; display and heading
 * families by their name (serif-looking names get the serif stack).
 */
export function fontStack(slot: Slot, name: string): string[] {
  const kind =
    slot === "mono"
      ? "mono"
      : slot === "serif" || ((slot === "display" || slot === "heading") && SERIF_NAME.test(name))
        ? "serif"
        : "sans";
  return [...new Set([name, ...STACK[kind]])];
}

/** CSS font-family value: generic keywords bare, names quoted. */
export function cssFontStack(stack: readonly string[]): string {
  return stack.map((f) => (GENERIC.has(f.toLowerCase()) ? f : JSON.stringify(f))).join(", ");
}

/** The family for a type step: headings use the heading/display face when there is one. */
export function familyForStep(
  families: ThemaSystem["typography"]["families"],
  step: string,
): { slot: Slot; name: string } {
  const pick = (...slots: Slot[]) => {
    for (const slot of slots) {
      const name = families[slot];
      if (name !== undefined) return { slot, name };
    }
    return { slot: "sans" as const, name: families.sans };
  };
  if (step === "4xl") return pick("display", "heading");
  if (step === "xl" || step === "2xl" || step === "3xl") return pick("heading", "display");
  return { slot: "sans", name: families.sans };
}

// --- provenance ---------------------------------------------------------------------------

export function sourceUrls(system: ThemaSystem): string[] {
  return system.meta.sources.map((s) => s.url).filter((url) => url !== "");
}

/** One line naming Thema's version and the sources, for every file's header. */
export function provenance(system: ThemaSystem): string {
  const urls = sourceUrls(system);
  return `Generated by Thema ${system.meta.version}${urls.length ? ` from ${urls.join(", ")}` : ""}.`;
}

export const px = (v: number): string => `${Math.round(v * 100) / 100}px`;
export const em = (v: number): string => `${Math.round(v * 1000) / 1000}em`;
