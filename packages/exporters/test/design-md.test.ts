import { lint } from "@google/design.md/linter";
import { describe, expect, it } from "vitest";
import { toDesignMd } from "../src/design-md.js";
import { COLOR_ROLES } from "../src/shared.js";
import { fixedSystem, fixtureNames } from "./fixtures.js";

const SECTIONS = [
  "Overview",
  "Colors",
  "Typography",
  "Layout",
  "Elevation & Depth",
  "Shapes",
  "Components",
  "Do's and Don'ts",
  "Motion",
  "Agent rules",
];

describe("DESIGN.md: Google's linter (@google/design.md 0.4.0)", () => {
  it.each(fixtureNames)("%s: no errors and no warnings", (name) => {
    const report = lint(toDesignMd(fixedSystem(name)));
    const notable = report.findings.filter((f) => f.severity !== "info");
    expect(notable, JSON.stringify(notable, null, 2)).toEqual([]);
    expect(report.summary.errors).toBe(0);
  });
});

describe("DESIGN.md: structure", () => {
  const md = toDesignMd(fixedSystem("light-saas"));
  const [, front = "", body = ""] = md.split(/^---$/m);

  it("starts with the provenance comment inside the front matter", () => {
    expect(md.startsWith("---\n# Generated by Thema ")).toBe(true);
  });

  it("lists every color role in light and as dark-<role>, as hex", () => {
    for (const role of COLOR_ROLES) {
      expect(front).toMatch(new RegExp(`^  ${role}: "#[0-9a-f]{6}"$`, "m"));
      expect(front).toMatch(new RegExp(`^  dark-${role}: "#[0-9a-f]{6}"$`, "m"));
    }
  });

  it("has the body sections in the spec's order, then Motion and Agent rules", () => {
    const headings = [...body.matchAll(/^## (.+)$/gm)].map((m) => m[1]);
    expect(headings).toEqual(SECTIONS);
  });

  it("keeps braces and angle brackets out of the prose (the linter parses it as MDX)", () => {
    expect(body).not.toMatch(/[{}<>]/);
  });

  it("matches the snapshot", () => {
    expect(md).toMatchSnapshot();
  });
});
