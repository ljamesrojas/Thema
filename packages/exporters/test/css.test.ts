import { parseCssColor } from "@thema/engine";
import { describe, expect, it } from "vitest";
import { SHADCN_VARIABLES, toShadcnCss, toTailwindCss } from "../src/css.js";
import { COLOR_ROLES, cssFontStack, fontStack } from "../src/shared.js";
import { fixedSystem, fixtureNames } from "./fixtures.js";

/** The `--name: value;` declarations inside one CSS block. */
function declarations(css: string, selector: string): Map<string, string> {
  const start = css.indexOf(`${selector} {`);
  const end = css.indexOf("\n}", start);
  const vars = new Map<string, string>();
  for (const m of css.slice(start, end).matchAll(/^ {2}--([\w-]+): (.+);$/gm)) {
    vars.set(m[1] ?? "", m[2] ?? "");
  }
  return vars;
}

describe("theme.css (Tailwind v4)", () => {
  const system = fixedSystem("light-saas");
  const css = toTailwindCss(system);

  it("defines every color in @theme and overrides them in .dark, in OKLCH", () => {
    const theme = declarations(css, "@theme");
    const dark = declarations(css, ".dark");
    for (const role of COLOR_ROLES) {
      expect(theme.get(`color-${role}`)).toBe(system.color.light[role]);
      expect(dark.get(`color-${role}`)).toBe(system.color.dark[role]);
    }
  });

  it("adds fallback stacks to font families, with generic keywords unquoted", () => {
    expect(declarations(css, "@theme").get("font-sans")).toBe(
      '"Inter", ui-sans-serif, system-ui, sans-serif',
    );
    expect(cssFontStack(fontStack("sans", "system-ui"))).toBe(
      "system-ui, ui-sans-serif, sans-serif",
    );
    // Display and heading faces get a stack by their name: Playfair and "Serif" names are serif.
    expect(fontStack("display", "Mozilla Headline")).toEqual([
      "Mozilla Headline",
      "ui-sans-serif",
      "system-ui",
      "sans-serif",
    ]);
    for (const name of ["Playfair Display", "Source Serif 4"]) {
      expect(fontStack("display", name)).toEqual([name, "ui-serif", "Georgia", "serif"]);
    }
  });

  it("has the type scale, radius, shadow, spacing unit, layout and motion", () => {
    const theme = declarations(css, "@theme");
    for (const step of system.typography.scale) {
      expect(theme.get(`text-${step.name}`)).toBe(`${step.size}px`);
      expect(theme.has(`text-${step.name}--line-height`)).toBe(true);
    }
    for (const name of [
      "radius-md",
      "shadow-md",
      "spacing",
      "container-max",
      "duration-fast",
      "ease-standard",
    ]) {
      expect(theme.has(name), name).toBe(true);
    }
  });

  it("starts with the provenance comment and matches the snapshot", () => {
    expect(css.startsWith("/* Tailwind v4 theme. Generated by Thema ")).toBe(true);
    expect(css).toMatchSnapshot();
  });
});

describe("shadcn.css", () => {
  it.each(fixtureNames)("%s: every shadcn variable in :root and .dark, as valid colors", (name) => {
    const css = toShadcnCss(fixedSystem(name));
    const root = declarations(css, ":root");
    const dark = declarations(css, ".dark");
    for (const variable of SHADCN_VARIABLES) {
      expect(root.has(variable), `:root --${variable}`).toBe(true);
      if (variable === "radius") continue;
      expect(parseCssColor(root.get(variable) ?? ""), variable).not.toBeNull();
      expect(parseCssColor(dark.get(variable) ?? ""), `.dark --${variable}`).not.toBeNull();
    }
  });

  it("maps shadcn's subtle accent to surface and Thema's accent to chart-2", () => {
    const system = fixedSystem("light-saas");
    const root = declarations(toShadcnCss(system), ":root");
    expect(root.get("accent")).toBe(system.color.light.surface);
    expect(root.get("chart-2")).toBe(system.color.light.accent);
    expect(root.get("primary-foreground")).toBe(system.color.light["primary-ink"]);
  });

  it("matches the snapshot", () => {
    expect(toShadcnCss(fixedSystem("light-saas"))).toMatchSnapshot();
  });
});
